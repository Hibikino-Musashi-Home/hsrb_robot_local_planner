constexpr double kWaitSec = 100.0;

constexpr double kEpsilonSec = 0.01;
constexpr double kEpsilonPos = 0.0001;

// time_from_start[sec] when optimizing the trajectory of GenerateSimpleGoal with default parameters
constexpr double kSimpleGoalTimeFromStart = 4.64;

moveit_msgs::msg::RobotTrajectory GenerateSimpleTrajectory() {
  // Trajectory to move 1.0[m] forward from a stationary state
  // If the robot is facing forward and stationary, it can reach the goal in about 4.64 seconds
  moveit_msgs::msg::RobotTrajectory robot_trajectory;
  robot_trajectory.joint_trajectory.joint_names = {"arm"};
  robot_trajectory.joint_trajectory.points.resize(2);
  robot_trajectory.joint_trajectory.points[0].positions = {0.0};
  robot_trajectory.joint_trajectory.points[0].velocities = {0.0};
  robot_trajectory.joint_trajectory.points[1].positions = {0.1};
  robot_trajectory.multi_dof_joint_trajectory.joint_names = {"odom"};
  robot_trajectory.multi_dof_joint_trajectory.points.resize(2);
  robot_trajectory.multi_dof_joint_trajectory.points[0].transforms.resize(1);
  robot_trajectory.multi_dof_joint_trajectory.points[0].transforms[0].rotation.w = 1.0;
  robot_trajectory.multi_dof_joint_trajectory.points[0].velocities.resize(1);
  robot_trajectory.multi_dof_joint_trajectory.points[1].transforms.resize(1);
  robot_trajectory.multi_dof_joint_trajectory.points[1].transforms[0].translation.x = 1.0;
  robot_trajectory.multi_dof_joint_trajectory.points[1].transforms[0].rotation.w = 1.0;
  return robot_trajectory;
}

void ValidateLastPoint(const moveit_msgs::msg::RobotTrajectory& trajectory,
                       bool do_velocity_check = true,
                       const std::string& joint_name = "arm") {
  // Assuming the goal generated by GenerateSimpleGoal
  // Since it becomes unclear from the message where the failure occurred, use only once in one test case
  ASSERT_EQ(1, trajectory.joint_trajectory.joint_names.size());
  EXPECT_EQ(joint_name, trajectory.joint_trajectory.joint_names[0]);

  auto last_joint_point = trajectory.joint_trajectory.points.back();
  ASSERT_EQ(1, last_joint_point.positions.size());
  EXPECT_NEAR(0.1, last_joint_point.positions[0], kEpsilonPos);

  if (do_velocity_check) {
    ASSERT_EQ(1, last_joint_point.velocities.size());
    EXPECT_NEAR(0.0, last_joint_point.velocities[0], kEpsilonPos);
  }

  ASSERT_EQ(1, trajectory.multi_dof_joint_trajectory.joint_names.size());
  EXPECT_EQ("odom", trajectory.multi_dof_joint_trajectory.joint_names[0]);

  auto last_base_point = trajectory.multi_dof_joint_trajectory.points.back();
  ASSERT_EQ(1, last_base_point.transforms.size());
  EXPECT_NEAR(1.0, last_base_point.transforms[0].translation.x, kEpsilonPos);

  if (do_velocity_check) {
    ASSERT_EQ(1, last_base_point.velocities.size());
    EXPECT_NEAR(0.0, last_base_point.velocities[0].linear.x, kEpsilonPos);
  }
}

void InitNode(rclcpp::Node::SharedPtr& node) {
  node->declare_parameter("optimize_timeout", 3.0);
  node->declare_parameter("arm.velocity", 1.0);
  node->declare_parameter("arm.acceleration", 1.0);
  node->declare_parameter("odom_x.velocity", 1.0);
  node->declare_parameter("odom_x.acceleration", 1.0);
  node->declare_parameter("odom_y.velocity", 1.0);
  node->declare_parameter("odom_y.acceleration", 1.0);
  node->declare_parameter("odom_t.velocity", 1.0);
  node->declare_parameter("odom_t.acceleration", 1.0);
}

void InitNode(rclcpp::Node::SharedPtr& server_node, rclcpp::Node::SharedPtr& client_node) {
  auto joint_state_publisher = client_node->create_publisher<sensor_msgs::msg::JointState>(
      "joint_states", rclcpp::SystemDefaultsQoS());
  auto odom_publisher = client_node->create_publisher<nav_msgs::msg::Odometry>(
      "odom", rclcpp::SystemDefaultsQoS());

  // Since there is no way to detect that the optimization node has received the topic, run it an appropriate number of times
  for (auto i = 0; i < 20; i++) {
    sensor_msgs::msg::JointState joint_state_msg;
    joint_state_msg.name = {"base_r_drive_wheel_joint", "base_l_drive_wheel_joint", "base_roll_joint"};
    joint_state_msg.position = {0.0, 0.0, 0.0};
    joint_state_msg.velocity = {0.0, 0.0, 0.0};
    joint_state_publisher->publish(joint_state_msg);

    nav_msgs::msg::Odometry odom_msg;
    odom_msg.pose.pose.orientation.w = 1.0;
    odom_publisher->publish(odom_msg);

    rclcpp::spin_some(client_node);
    rclcpp::spin_some(server_node);
    std::this_thread::sleep_for(std::chrono::milliseconds(1));
  }
}


// Use of optimizer that goes through a stop
TEST_F(OptimizerNodeTest, OptimizeViaStop) {
  // Optimization with initial speed in the reverse direction
  auto robot_trajectory = GenerateSimpleTrajectory();
  robot_trajectory.multi_dof_joint_trajectory.points.front().velocities.front().linear.x = -0.05;

  auto result = SendGoalSync(robot_trajectory, action_msgs::msg::GoalStatus::STATUS_SUCCEEDED);
  ValidateLastPoint(result);
  const auto duration_normal = rclcpp::Duration(result.joint_trajectory.points.back().time_from_start).seconds();

  server_node_->set_parameter(rclcpp::Parameter("acceleration_rate_for_stop", 2.0));

  result = SendGoalSync(robot_trajectory, action_msgs::msg::GoalStatus::STATUS_SUCCEEDED);
  ValidateLastPoint(result);
  const auto duration_via_stop = rclcpp::Duration(result.joint_trajectory.points.back().time_from_start).seconds();

  // Since it is initial speed in the reverse direction, it should be in the order of zero initial speed, full stop, and normal optimization
  EXPECT_LT(kSimpleGoalTimeFromStart + kEpsilonSec, duration_via_stop);
  EXPECT_LT(duration_via_stop, duration_normal);
}

// Test of action cancellation
TEST_F(OptimizerNodeTest, PreemptActionGoal) {
  tmc_planning_msgs::action::OptimizeRobotTrajectory::Goal goal;
  goal.robot_trajectory = GenerateSimpleTrajectory();
  for (auto i = 0; i < 100; ++i) {
    goal.robot_trajectory.joint_trajectory.points.push_back(goal.robot_trajectory.joint_trajectory.points[0]);
    goal.robot_trajectory.joint_trajectory.points.push_back(goal.robot_trajectory.joint_trajectory.points[1]);
    goal.robot_trajectory.multi_dof_joint_trajectory.points.push_back(
        goal.robot_trajectory.multi_dof_joint_trajectory.points[0]);
    goal.robot_trajectory.multi_dof_joint_trajectory.points.push_back(
        goal.robot_trajectory.multi_dof_joint_trajectory.points[1]);
  }

  auto future_goal_handle = client_->async_send_goal(goal);
  WaitForFutureComplete(future_goal_handle);

  auto goal_handle = future_goal_handle.get();
  EXPECT_TRUE(goal_handle.get());

  auto future_cancel_response = client_->async_cancel_goal(goal_handle);
  WaitForFutureComplete(future_cancel_response);

  auto future_result = client_->async_get_result(goal_handle);
  WaitForFutureComplete(future_result);

  auto wrapped_result = future_result.get();
  EXPECT_EQ(static_cast<int8_t>(wrapped_result.code), action_msgs::msg::GoalStatus::STATUS_CANCELED);
}


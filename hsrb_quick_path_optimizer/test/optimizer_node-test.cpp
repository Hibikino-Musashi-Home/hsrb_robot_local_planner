// Optimization of forward movement from a stationary state, with both the robot and the cart facing forward
TEST_F(OptimizerNodeTest, OptimizeSimpleTrajectory) {
  auto result = SendGoalSync(GenerateSimpleTrajectory(), action_msgs::msg::GoalStatus::STATUS_SUCCEEDED);
  ValidateLastPoint(result);

  // It should be 4.64 seconds, so ideally it should be 47 points
  ASSERT_EQ(47, result.joint_trajectory.points.size());
  EXPECT_EQ(result.multi_dof_joint_trajectory.points.size(),
            result.joint_trajectory.points.size());

  EXPECT_NEAR(kSimpleGoalTimeFromStart,
              rclcpp::Duration(result.joint_trajectory.points.back().time_from_start).seconds(), kEpsilonSec);
  EXPECT_NEAR(kSimpleGoalTimeFromStart,
              rclcpp::Duration(result.multi_dof_joint_trajectory.points.back().time_from_start).seconds(), kEpsilonSec);

  auto first_joint_point = result.joint_trajectory.points.front();
  EXPECT_NEAR(0.1, rclcpp::Duration(first_joint_point.time_from_start).seconds(), kEpsilonSec);
  // The cart part determines the operation time
  // What kind of acceleration the arm part will have depends on the optimization algorithm,
  // Ensure that it is working properly and does not exceed the maximum acceleration of 1.0
  ASSERT_EQ(1, first_joint_point.positions.size());
  EXPECT_LT(0.0, first_joint_point.positions[0]);
  EXPECT_GE(0.5 * 1.0 * 0.1 * 0.1, first_joint_point.positions[0]);

  ASSERT_EQ(1, first_joint_point.velocities.size());
  EXPECT_LT(0.0, first_joint_point.velocities[0]);
  EXPECT_GE(1.0 * 0.1, first_joint_point.velocities[0]);

  auto first_base_point = result.multi_dof_joint_trajectory.points.front();
  EXPECT_NEAR(0.1, rclcpp::Duration(first_base_point.time_from_start).seconds(), kEpsilonSec);

  // Check if the cart part is producing the maximum acceleration of 0.2 due to the mechanism
  ASSERT_EQ(1, first_base_point.transforms.size());
  EXPECT_NEAR(0.5 * 0.2 * 0.1 * 0.1,
              first_base_point.transforms[0].translation.x, kEpsilonPos);

  ASSERT_EQ(1, first_base_point.velocities.size());
  EXPECT_NEAR(0.2 * 0.1, first_base_point.velocities[0].linear.x, kEpsilonPos);
}

